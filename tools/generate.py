def to_rust_identifier(name: str) -> str:
    """Convert an icon name into a Rust function identifier."""

    name = re.sub(r"[^a-zA-Z0-9_]", "_", name)
    name = re.sub(r"_+", "_", name).strip("_").lower()

    if not name:
        raise ValueError("Icon name produces an empty Rust identifier.")

    if name[0].isdigit():
        name = f"icon_{name}"

    if name in RUST_KEYWORDS:
        name = f"icon_{name}"

    return name


def load_icons(selection_path: Path, weight: str) -> list[tuple[str, int]]:
    """Extract icon names and codepoints from selection.json."""

    with selection_path.open("r", encoding="utf-8") as file:
        data = json.load(file)

    if not isinstance(data, dict) or not isinstance(data.get("icons"), list):
        raise TypeError(f"Invalid selection.json: {selection_path}")

    icons = []
    seen_names = set()

    for entry in data["icons"]:
        if not isinstance(entry, dict):
            raise TypeError(f"Invalid icon entry in {selection_path}")

        properties = entry.get("properties", {})

        if not isinstance(properties, dict):
            raise TypeError(f"Invalid icon properties in {selection_path}")

        original_name = properties.get("name")
        codepoint = properties.get("code")

        if not isinstance(original_name, str) or not original_name:
            raise ValueError(f"Missing icon name in {selection_path}")

        if (
            isinstance(codepoint, bool)
            or not isinstance(codepoint, int)
            or not 0 <= codepoint <= 0x10FFFF
            or 0xD800 <= codepoint <= 0xDFFF
        ):
            raise ValueError(f"Invalid Unicode codepoint for icon {original_name!r}")

        # Remove the font-weight suffix when present.
        # The directory name determines the font weight.
        suffix = f"-{weight}"

        if original_name.endswith(suffix):
            original_name = original_name.removesuffix(suffix)

        function_name = to_rust_identifier(original_name)

        if function_name in seen_names:
            raise ValueError(
                f"Duplicate function name {function_name!r} in {selection_path}"
            )

        seen_names.add(function_name)
        icons.append((function_name, codepoint))

    return icons


def generate_module(weight: str, icons: list[tuple[str, int]]) -> str:
    """Generate the Rust module for one font weight."""

    font_constant = f"FONT_{weight.upper()}"

    lines = [
        "// @generated by tools/generate.py. Do not edit manually.",
        f"//! Phosphor icons using the {weight} font.",
        "",
        "use iced::widget::Text;",
        "use crate::icon::{create_icon};",
        f"use crate::icon::{font_constant};",
        "",
    ]

    for name, codepoint in icons:
        description = name.replace("_", " ")

        lines.extend(
            [
                f"/// Returns the `{description}` icon.",
                f"pub fn {name}() -> Text<'static> {{",
                f"    create_icon(0x{codepoint:X}, {font_constant})",
                "}",
                "",
            ]
        )

    return "\n".join(lines)


def main() -> int:
    if not ASSETS_DIR.is_dir():
        print(f"Error: assets directory not found: {ASSETS_DIR}", file=sys.stderr)
        return 1

    if not SRC_DIR.is_dir():
        print(f"Error: src directory not found: {SRC_DIR}", file=sys.stderr)
        return 1

    # Each immediate subdirectory represents a font weight.
    weight_dirs = sorted(path for path in ASSETS_DIR.iterdir() if path.is_dir())

    if not weight_dirs:
        print("Error: no font directories found.", file=sys.stderr)
        return 1

    try:
        for weight_dir in weight_dirs:
            weight = weight_dir.name

            # Ensure the directory name is a valid Rust module identifier.
            if (
                not re.fullmatch(r"[a-zA-Z_][a-zA-Z0-9_]*", weight)
                or keyword.iskeyword(weight)
                or weight in RUST_KEYWORDS
            ):
                raise ValueError(f"Invalid Rust module name: {weight!r}")

            selection_path = weight_dir / "selection.json"

            if not selection_path.is_file():
                raise ValueError(f"Missing selection.json in {weight_dir}")

            icons = load_icons(selection_path, weight)

            output_path = SRC_DIR / f"{weight}.rs"
            source = generate_module(weight, icons)

            output_path.write_text(source, encoding="utf-8")

            print(f"Generated src/{weight}.rs ({len(icons)} icons)")

    except (OSError, json.JSONDecodeError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    print("Font module generation completed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
